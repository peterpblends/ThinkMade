/**
 * Writes src/cover-glyphs.ts: Newsreader 600 glyph outlines (Latin, at 1000 units per em) and their advance
 * widths, so show artwork can set any title in the brand typeface without loading a font at run time.
 *   npx tsx packages/brand/scripts/build-cover-glyphs.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const buf = readFileSync(require.resolve('@fontsource/newsreader/files/newsreader-latin-600-normal.woff'));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const UNITS = 1000;
const scale = UNITS / font.unitsPerEm;

// Printable ASCII, Latin-1 letters and the punctuation titles use.
const chars = new Set<string>();
for (let c = 0x20; c <= 0x7e; c++) chars.add(String.fromCharCode(c));
for (let c = 0xc0; c <= 0xff; c++) if (c !== 0xd7 && c !== 0xf7) chars.add(String.fromCharCode(c));
for (const c of '‘’“”–—…•·¿¡€£') chars.add(c);

const glyphs: Record<string, [number, string]> = {};
for (const ch of chars) {
  const g = font.charToGlyph(ch);
  if (!g || g.index === 0) continue;
  const path = g.getPath(0, 0, UNITS);
  glyphs[ch] = [Math.round((g.advanceWidth ?? 0) * scale), path.toPathData(0)];
}
const capHeight = Math.round(((font.tables.os2 as { sCapHeight?: number }).sCapHeight ?? font.ascender * 0.7) * scale);
const out = `// Generated by scripts/build-cover-glyphs.ts from Newsreader 600 (SIL Open Font License). Do not edit.
/** Units per em of the glyph paths; the baseline is y = 0 and y grows downwards. */
export const COVER_FONT_UNITS = ${UNITS};
export const COVER_FONT_CAP_HEIGHT = ${capHeight};
/** Character → [advance width, SVG path data]. */
export const COVER_GLYPHS: Record<string, [number, string]> = ${JSON.stringify(glyphs)};
`;
writeFileSync(join(here, '..', 'src', 'cover-glyphs.ts'), out);
console.info(`${Object.keys(glyphs).length} glyphs, ${Math.round(out.length / 1024)} KB`);
